-- Immutable per-forecast error diagnoses.
-- Additive: does not alter existing shop, quote, news, or forecast records.

create table if not exists public.market_forecast_error_diagnostics (
  id bigint generated by default as identity primary key,
  forecast_id uuid not null references public.market_forecast_runs(id) on delete cascade,
  asset text not null,
  horizon_days integer not null check (horizon_days in (1,3,7)),
  model_version text not null,
  diagnosed_at timestamptz not null default now(),
  error_metrics jsonb not null default '{}'::jsonb,
  contributing_factors jsonb not null default '{}'::jsonb,
  root_cause_candidates jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now(),
  unique (forecast_id)
);

create index if not exists market_forecast_error_diagnostics_asset_idx
  on public.market_forecast_error_diagnostics (asset, horizon_days, diagnosed_at desc);

create index if not exists market_forecast_error_diagnostics_candidates_idx
  on public.market_forecast_error_diagnostics using gin (root_cause_candidates);

alter table public.market_forecast_error_diagnostics enable row level security;
revoke all on public.market_forecast_error_diagnostics from anon, authenticated;
grant select, insert on public.market_forecast_error_diagnostics to service_role;
grant usage, select on sequence public.market_forecast_error_diagnostics_id_seq to service_role;
